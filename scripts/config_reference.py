"""Render the config.toml reference from the schema and starter file."""

from __future__ import annotations

import json
from collections.abc import Iterable, Iterator, Set

from pydantic import BaseModel

from dom.config import Config, DesktopConfig, DesktopHost, ModelEndpoint, OpenersConfig, PresenceConfig, SelfWorkConfig, T3Config, UpdateConfig, WebConfig, starter_config

MODEL_ROLES = {
    "chat": ("Required", "Primary chat and desktop worker model."),
    "chat_fallback": ("Optional", "Backup chat endpoint when the primary is unavailable."),
    "triage": ("Built in", "Jev Decisions endpoint for triage (whether, when and how urgently to reply), the outbound leak check on replies and online plugin calls, the rescue of a chat reply written as plain prose, and the `dom doctor --online` probe."),
    "media": ("Built in", "Attachment descriptions, transcriptions and desktop screenshot descriptions."),
    "search": ("Optional", "OpenRouter web search. If the table is present, omitted fields use the starter search settings."),
}


def literal(value: object) -> str:
    return f"`{json.dumps(value, ensure_ascii=False)}`" if value is not None else "Unset"


def fields(
    model: type[BaseModel], prefix: str = "", *, exclude: Set[str] = frozenset(),
) -> Iterator[tuple[str, str, str | None]]:
    for key, field in model.model_fields.items():
        if key in exclude:
            continue
        if field.is_required():
            default = "Required"
        elif field.default_factory_takes_validated_data:
            default = "Derived"
        else:
            default = literal(field.get_default(call_default_factory=True))
        yield prefix + key, default, field.description


def table(rows: Iterable[tuple[str, str, str | None]]) -> str:
    lines = ["| Key | Default | Meaning |", "| --- | --- | --- |"]
    for key, default, meaning in rows:
        if not meaning:
            raise ValueError(f"{key} needs a description in the config model")
        lines.append(f"| `{key}` | {default} | {meaning} |")
    return "\n".join(lines)


def render() -> str:
    sections = [
        "# Configuration",
        "<!-- Generated by scripts/config_reference.py. -->",
        "Dom reads `config.toml` from the instance home. Put secret values in `.env` "
        "or the process environment. Dom checks `.env` first.",
        "Regenerate this file from the checkout after changing an option.",
        "```sh\nuv run python scripts/config_reference.py > docs/configuration.md\n```",
        "## Top-level keys",
        table(fields(Config, exclude={"home", "desktop_mode", "models", "desktop", "openers", "presence", "self_work", "web", "t3", "update"})),
        "## Models",
        table((f"models.{key}", default, meaning) for key, (default, meaning) in MODEL_ROLES.items()),
        "Each `[models.<name>]` table uses the following keys. Use HTTPS for a provider on a different host.",
        table(fields(ModelEndpoint, "models.<name>.")),
        "### Starter model settings",
        "Init creates the four tables below. Omitted triage and media tables use these defaults. "
        "A hand-written config must supply `[models.chat]`. Omitting `[models.search]` disables search.",
        table(
            (f"models.{role}.{key}", literal(value), ModelEndpoint.model_fields[key].description)
            for role, settings in starter_config()["models"].items()
            for key, value in settings.items()
        ),
        "## Optional secrets",
        "`KLIPY_API_KEY` turns on GIF sending. Without it Dom does not offer the `gif` action. See [GIFs](gifs.md).",
        "## Desktop",
        table([
            ("desktop.mode", literal(Config.model_fields["desktop_mode"].default),
             Config.model_fields["desktop_mode"].description),
            *fields(DesktopConfig, "desktop."),
        ]),
        "### Desktop hosts",
        "Add one `[[desktop.hosts]]` table per host. A local host runs Docker containers on this machine "
        "(list at most one). A remote host is one sandbox API and counts as one container, named after the host. "
        "Without any `[[desktop.hosts]]`, `desktop.mode` and the keys above describe a single host named `default`.",
        table(fields(DesktopHost, "desktop.hosts[].")),
        "## Openers",
        table(fields(OpenersConfig, "openers.")),
        "## Presence",
        table(fields(PresenceConfig, "presence.")),
        "## Self-directed work",
        table(fields(SelfWorkConfig, "self_work.")),
        "See [Self-directed work](desktop.md#self-directed-work) for the network guard it needs and what it may do.",
        "## Web",
        table(fields(WebConfig, "web.")),
        "## T3 Code",
        table(fields(T3Config, "t3.")),
        "See the [T3 Code bridge guide](t3-bridge.md) for service setup and CLI compatibility.",
        "## Update",
        table(fields(UpdateConfig, "update.")),
        "See [Deploy on a Raspberry Pi](deploy-pi.md) for how `/update` and `dom deploy` switch releases.",
        "See the [setup guide](setup.md) for examples and [Privacy](privacy.md) for how Dom uses the configured services.",
    ]
    return "\n\n".join(sections) + "\n"


if __name__ == "__main__":
    print(render(), end="")
