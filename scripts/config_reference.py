def literal(value: object) -> str:
    return f"`{json.dumps(value, ensure_ascii=False)}`" if value is not None else "Unset"


def fields(
    model: type[BaseModel], prefix: str = "", *, exclude: Set[str] = frozenset(),
) -> Iterator[tuple[str, str, str | None]]:
    for key, field in model.model_fields.items():
        if key in exclude:
            continue
        if field.is_required():
            default = "Required"
        elif field.default_factory_takes_validated_data:
            default = "Derived"
        else:
            default = literal(field.get_default(call_default_factory=True))
        yield prefix + key, default, field.description


def table(rows: Iterable[tuple[str, str, str | None]]) -> str:
    lines = ["| Key | Default | Meaning |", "| --- | --- | --- |"]
    for key, default, meaning in rows:
        if not meaning:
            raise ValueError(f"{key} needs a description in the config model")
        lines.append(f"| `{key}` | {default} | {meaning} |")
    return "\n".join(lines)


